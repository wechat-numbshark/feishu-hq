BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'hq_app') THEN
    CREATE ROLE hq_app NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
  END IF;
END;
$$;

GRANT USAGE ON SCHEMA platform, authz, integration, audit TO hq_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA platform TO hq_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA authz TO hq_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA integration TO hq_app;
GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA audit TO hq_app;
REVOKE ALL ON platform.schema_migrations FROM hq_app;

ALTER DEFAULT PRIVILEGES IN SCHEMA platform
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO hq_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA authz
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO hq_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA integration
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO hq_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA audit
  GRANT SELECT, INSERT ON TABLES TO hq_app;

COMMIT;

